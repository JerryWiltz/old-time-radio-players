  <h1>The Whistler - 22 Mp3 Downloads Available</h1>
  <img src="/images/The Whistler.jpg" align=left alt="The Whistler - OTR Picture">  <strong>"The Whistler"</strong> was an American radio program running for a total of 13 years from May 16, 1942 until September 22, 1955.  It was one of the most popular mystery drama's of its' time.  Signal Oil Company sponsored the program.  The marketing catch phrase was: "Let that whistle be your signal for the Signal Oil program, The Whistler."
<br>
<br>During the first two years of the show J. Donald Wilson was the writer and producer. During 1944 producer and director George Allen took over.  Other directors included Sterling Tracy and Sherman Marks with final scripts by Joel Malone and Harold Swanton. 692 total episodes were produced.  Over 200 of those episodes can not be found and are no longer in existence. 
<br>
<br><strong>Episodes of The Whistler began with the ominous narration:</strong>
<br>I am the Whistler, and I know many things, for I walk by night. I know many strange tales, many secrets hidden in the hearts of men and women who have stepped into the shadows. I know the nameless terrors of which they dare not speak. 
<br>
<br>Those opening words were spoken along with the echo of footsteps and Wilbur Hatch's 13-note theme, whistled weekly by Dorothy Roberts for 13 years. Bill Forman had the title role of host and narrator. Others who portrayed the Whistler at various times were Gale Gordon (Lucille Ball's future television nemesis), Joseph Kearns (played Mr. Wilson on TV series Dennis the Menace), Marvin Miller (soon the announcer for The Bickersons and, later, television's Michael Anthony on The Millionaire), Bill Johnstone (who played The Shadow on radio 1938-1943) and Everett Clarke.
<br>
<br>The stories followed an effective formula in which a person's criminal acts were typically undone by their own stupidity. Ironic twist endings were common, as they had been on the show that most obviously influenced it[citation needed], The Shadow. The Whistler narrated, often commenting directly upon the action in the manner of a Greek chorus, taunting the criminal from an omniscient perspective. The Whistler seldom featured any major Hollywood stars, but the quality of writing and performance made it a radio mainstay.  <div class="clear"></div>
